#!/usr/bin/env python3
"""LyricsFlow port: LyricsFlow 2.1's live_sky.fsh (374m, MIT) -> one dialect-neutral body + two thin preludes.

  python tools/LyricsSky/gen_sky_shaders.py            (from the repo root)

Writes
  resources/lyricsflow/shaders/live_sky.hlsl   HLSL for Renderer Foundation (compiled by dxc in RF's CI)
  tools/LyricsSky/out/live_sky_check.glsl      GLSL ES built from the SAME body; render_sky.js --check compares it
                                               pixel-for-pixel with the original shader, which proves the rewrites
The rewrites are mechanical: single-argument vector constructors -> SPLATn(), two-argument atan -> atan2, mat2 * v ->
MUL2(), globals -> GLOBAL / GCONST, a few names that clash with HLSL (noise, line, lit), texelFetch -> PX_FETCH and
main() -> skyMain(). Everything else (maths, constants, branch order) is left byte-for-byte.
"""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / 'resources/lyricsflow/shaders/live_sky.fsh'


def args_end(s, i):
    """s[i] == '(' -> index of the matching ')' and the top-level comma count."""
    depth, commas = 0, 0
    for j in range(i, len(s)):
        c = s[j]
        if c == '(':
            depth += 1
        elif c == ')':
            depth -= 1
            if depth == 0:
                return j, commas
        elif c == ',' and depth == 1:
            commas += 1
    raise ValueError('unbalanced')


def rewrite_calls(s, name_re, fn):
    out, pos = [], 0
    for m in re.finditer(name_re, s):
        if m.start() < pos:
            continue
        open_i = m.end() - 1
        close_i, commas = args_end(s, open_i)
        rep = fn(m, s[open_i + 1:close_i], commas)
        if rep is None:
            continue
        out.append(s[pos:m.start()]); out.append(rep); pos = close_i + 1
    out.append(s[pos:])
    return ''.join(out)


def neutral(src):
    lines = src.split('\n')
    # drop the GLSL header (version, uniform, in/out) - preludes provide them
    body = '\n'.join(l for l in lines if not re.match(r'\s*(#version|uniform |in vec3 |out vec4 )', l))
    for a, b in (('noise', 'lfNoise'), ('line', 'lfLine'), ('lit', 'lfLit')):
        body = re.sub(r'\b%s\b' % a, b, body)
    body = body.replace('texelFetch(Sampler0, ivec2(i, 0), 0)', 'PX_FETCH(i)')
    body = body.replace('p = m * p;', 'p = MUL2(m, p);')
    if 'MUL2' not in body:
        sys.exit('mat2 multiply not found')
    # globals (file scope, before the first function)
    first_fn = re.search(r'^\w+ \w+\([^)]*\) *\{', body, re.M).start()
    head, rest = body[:first_fn], body[first_fn:]
    head = re.sub(r'^const ', 'GCONST ', head, flags=re.M)
    head = re.sub(r'^(vec3|int|float) ', r'GLOBAL \1 ', head, flags=re.M)
    body = head + rest
    # single-argument vector constructors -> SPLAT
    def splat(m, inner, commas):
        if commas:
            return None
        n = m.group(2)
        return 'SPLAT%s%s(%s)' % ('I' if m.group(1) else '', n, inner)
    for _ in range(4):  # nested
        body = rewrite_calls(body, r'\b(i?)vec([234])\(', splat)
    body = rewrite_calls(body, r'\batan\(', lambda m, inner, c: ('atan2(%s)' % inner) if c == 1 else None)
    # main -> skyMain
    body = body.replace('void main() {', 'vec4 skyMain(vec3 skyDir, vec3 skyInfo) {')
    body = body.replace('fragColor = vec4(col, a);', 'return vec4(col, a);')
    if 'skyMain' not in body or 'return vec4(col, a);' not in body:
        sys.exit('main() shape changed')
    return body


HLSL_PRELUDE = r'''// Generated by tools/LyricsSky/gen_sky_shaders.py from live_sky.fsh (LyricsFlow 2.1 by 374m, MIT) - do not edit.
// Pixel shader body for Renderer Foundation's live-sky pass. Include it after declaring
//   Texture2D<float4> gSkyParams   (16 x 1 RGBA8_UNORM, Sky::pack)
#define vec2 float2
#define vec3 float3
#define vec4 float4
#define ivec2 int2
#define mat2 float2x2
#define fract frac
#define mix lerp
#define inversesqrt rsqrt
#define GLOBAL static
#define GCONST static const
#define SPLAT2(x) ((float2)(x))
#define SPLAT3(x) ((float3)(x))
#define SPLAT4(x) ((float4)(x))
#define SPLATI2(x) ((int2)(x))
#define PX_FETCH(i) gSkyParams.Load(int3((i), 0, 0))
// GLSL mat2(a, b, c, d) is column-major: m * v == mul(v, float2x2(a, b, c, d))
#define MUL2(m, v) mul((v), (m))
float  mod(float x, float y)   { return x - y * floor(x / y); }
float2 mod(float2 x, float y)  { return x - y * floor(x / y); }
float3 mod(float3 x, float y)  { return x - y * floor(x / y); }
float2 mod(float2 x, float2 y) { return x - y * floor(x / y); }
float3 mod(float3 x, float3 y) { return x - y * floor(x / y); }
'''

GLSL_PRELUDE = r'''#version 300 es
// Generated check build: the neutral body with a GLSL prelude (must match live_sky.fsh pixel for pixel).
precision highp float;
precision highp int;
precision highp sampler2D;
uniform sampler2D Sampler0;
in vec3 skyDir;
in vec3 skyInfo;
out vec4 fragColor;
#define GLOBAL
#define GCONST const
#define SPLAT2(x) vec2(x)
#define SPLAT3(x) vec3(x)
#define SPLAT4(x) vec4(x)
#define SPLATI2(x) ivec2(x)
#define PX_FETCH(i) texelFetch(Sampler0, ivec2((i), 0), 0)
#define MUL2(m, v) ((m) * (v))
#define atan2 atan
'''


def main():
    body = neutral(SRC.read_text())
    (ROOT / 'resources/lyricsflow/shaders/live_sky.hlsl').write_text(HLSL_PRELUDE + body + '\n')
    out = ROOT / 'tools/LyricsSky/out'
    out.mkdir(exist_ok=True)
    (out / 'live_sky_check.glsl').write_text(GLSL_PRELUDE + body + '\nvoid main() { fragColor = skyMain(skyDir, skyInfo); }\n')
    print('ok', len(body.splitlines()), 'lines')


if __name__ == '__main__':
    main()
