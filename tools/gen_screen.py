#!/usr/bin/env python3
"""Compile the LyricsForge video screen shaders to bytecode and write src/ScreenShaders.h.
Usage: python3 tools/gen_screen.py path/to/dxc [path/to/fxc]
  shaders/screen.hlsl  -> VSFit / PSFit (DXIL; + SM5 VSFit11 / PSFit11 with fxc for the D3D11 path)
  shaders/anime4k.hlsl -> A4K_VS + one pixel shader per Anime4K pass (DXIL; D3D12 only), list in tools/anime4k_entries.txt
CI runs this before the build (same step as gen_glyph.py)."""
import pathlib, subprocess, sys, tempfile

root = pathlib.Path(__file__).resolve().parent.parent
dxc = sys.argv[1] if len(sys.argv) > 1 else "dxc"
fxc = sys.argv[2] if len(sys.argv) > 2 else None
a4k = [e.strip() for e in (root / "tools/anime4k_entries.txt").read_text().split() if e.strip()]
jobs = [("VSFit", "vs_6_0", "shaders/screen.hlsl"), ("PSFit", "ps_6_0", "shaders/screen.hlsl"),
        ("A4K_VS", "vs_6_0", "shaders/anime4k.hlsl")] + [(e, "ps_6_0", "shaders/anime4k.hlsl") for e in a4k]


def rows(b):
    return ",\n    ".join(", ".join(f"0x{x:02x}" for x in b[i:i + 20]) for i in range(0, len(b), 20))


out = ["// Generated by tools/gen_screen.py from shaders/screen.hlsl + shaders/anime4k.hlsl - do not edit.",
       "// Anime4K by bloc97 (MIT): see shaders/anime4k.hlsl.", "#pragma once", "#include <cstdint>", "",
       "#define RF_HAVE_SCREEN_SHADERS 1", "namespace rf::screen::shaders {"]
with tempfile.TemporaryDirectory() as td:
    for name, prof, src in jobs:
        o = pathlib.Path(td) / f"{name}.dxil"
        subprocess.run([dxc, "-T", prof, "-E", name, "-O3", "-Fo", str(o), str(root / src)], check=True)
        b = o.read_bytes()
        assert b[4:20] != bytes(16), f"{name}: unsigned DXIL (dxc without libdxil/dxil.dll)"
        out.append(f"inline constexpr uint8_t {name}[{len(b)}] = {{\n    {rows(b)}\n}};")
    if fxc:
        for name, prof in [("VSFit", "vs_5_0"), ("PSFit", "ps_5_0")]:
            o = pathlib.Path(td) / f"{name}.dxbc"
            subprocess.run([fxc, "/nologo", "/T", prof, "/E", name, "/O3", "/Fo", str(o), str(root / "shaders/screen.hlsl")], check=True)
            out.append(f"inline constexpr uint8_t {name}11[{len(o.read_bytes())}] = {{\n    {rows(o.read_bytes())}\n}};")
        out.insert(6, "#define RF_HAVE_SCREEN_SHADERS11 1")
# entry name -> bytecode, in tools/anime4k_entries.txt order (= kA4kPasses order)
out.append("struct A4kCode { uint8_t const* code; uint32_t size; };")
out.append("inline constexpr A4kCode kA4kCode[] = {" + ", ".join(f"{{{e}, sizeof {e}}}" for e in a4k) + "};")
out.append("} // namespace rf::screen::shaders\n")
(root / "src/ScreenShaders.h").write_text("\n".join(out))
print(f"wrote src/ScreenShaders.h ({len(jobs)} DXIL shaders)")
