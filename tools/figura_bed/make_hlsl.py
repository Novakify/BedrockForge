# Bakes a Figura avatar's pose into capsules for the "Your Figura" cosmetic bed (worldfx_pass.hlsl).
# usage: python bake_pose.py figura_avatar.json <time> <animation index>  ->  posed_<anim>_<time>.pkl
#        python make_hlsl.py posed.pkl ../../shaders/figura_bed.hlsli
# Each limb mesh becomes one capsule (principal axis of its vertices); the head mesh becomes a sphere.
import pickle, sys, numpy as np
d = pickle.load(open(sys.argv[1], 'rb'))
caps = []
for n, v, path in d:
    if n in ('TSC', 'TCO', 'TDL', 'Victim'): continue      # the avatar's name-tag cards (hidden by its script)
    if n == 'sphere':
        if len(v) < 300: continue                             # the flat face ring; the round head is the big one
        A = np.c_[2 * v, np.ones(len(v))]; x = np.linalg.lstsq(A, (v ** 2).sum(1), rcond=None)[0]
        c = x[:3]; caps.append((c, c, float(np.sqrt(x[3] + c @ c)), 0)); continue
    m = v.mean(0); ax = np.linalg.svd(v - m)[2][0]
    t = (v - m) @ ax; r = float(np.percentile(np.linalg.norm((v - m) - np.outer(t, ax), axis=1), 75))
    a = m + ax * (t.min() + r * 0.6); b = m + ax * (t.max() - r * 0.6)
    part = 2 if 'Arm' in path else 1
    caps.append((a, b, r, part))
# part: 0 head, 1 body / legs, 2 arms (rise with the breath)
caps.sort(key=lambda c: c[3])
caps[1:] = sorted(caps[1:], key=lambda c: -max(c[0][1], c[1][1]))
f = open(sys.argv[2], 'w')
f.write('// generated by tools/figura_bed/make_hlsl.py from the Figura avatar "stick" (its sitdown pose): units = Figura pixels\n')
f.write('#define FIG_N %d\n' % len(caps))
f.write('static const float4 kFigA[FIG_N] = {\n' + ',\n'.join('    float4(%.3f, %.3f, %.3f, %.3f)' % (*c[0], c[2]) for c in caps) + '};\n')
f.write('static const float4 kFigB[FIG_N] = {\n' + ',\n'.join('    float4(%.3f, %.3f, %.3f, %d)' % (*c[1], c[3]) for c in caps) + '};\n')
f.close()
for c in caps: print(np.round(c[0],2), np.round(c[1],2), round(c[2],2), c[3])
