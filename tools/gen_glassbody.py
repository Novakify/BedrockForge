#!/usr/bin/env python3
"""Glass Body: compile shaders/glass_body.hlsl to signed DXIL and write src/GlassBodyShaders.h, plus the player
model's face table (classic + slim, base + second layer) in shaders/glass_body_data.hlsli.

The face table must match src/GlassBodyMath.h (playerCubes / cubeFaces) - tools/glassbody_test.cpp checks that one.
Usage: python3 tools/gen_glassbody.py [path/to/dxc] [--no-compile]
"""
import pathlib
import subprocess
import sys
import tempfile

root = pathlib.Path(__file__).resolve().parent.parent
args = [a for a in sys.argv[1:] if not a.startswith("--")]
dxc = args[0] if args else "dxc"
compile_ = "--no-compile" not in sys.argv


def cubes(slim):
    a = 3 if slim else 4
    return [(0, 0, 8, 8, 8, 0), (32, 0, 8, 8, 8, 1), (16, 16, 8, 12, 4, 0), (16, 32, 8, 12, 4, 1),
            (40, 16, a, 12, 4, 0), (40, 32, a, 12, 4, 1), (32, 48, a, 12, 4, 0), (48, 48, a, 12, 4, 1),
            (0, 16, 4, 12, 4, 0), (0, 32, 4, 12, 4, 1), (16, 48, 4, 12, 4, 0), (0, 48, 4, 12, 4, 1)]


def faces(c):
    u, v, w, h, d, ov = c
    return [(u + d, v, w, d), (u + d + w, v, w, d), (u, v + d, d, h), (u + d, v + d, w, h), (u + d + w, v + d, d, h),
            (u + 2 * d + w, v + d, w, h)]


hl = ["// Generated by tools/gen_glassbody.py - do not edit.",
      "// 12 cubes x 6 faces: int4(x, y, w, h) in 64x64 texels; face i belongs to cube i / 6, odd cubes are the second layer"]
for name, slim in (("kBodyFaces", False), ("kBodyFacesSlim", True)):
    fs = [f for c in cubes(slim) for f in faces(c)]
    assert len(fs) == 72
    hl.append(f"static const int4 {name}[72] = {{" + ", ".join(f"int4({a},{b},{c},{d})" for a, b, c, d in fs) + "};")
(root / "shaders/glass_body_data.hlsli").write_text("\n".join(hl) + "\n")

def build(src, entry, td):
    if not compile_:
        return b"\0"
    o = pathlib.Path(td) / (entry + ".dxil")
    subprocess.run([dxc, "-T", "ps_6_0", "-E", entry, "-O3", "-I", str(root / "shaders"), "-Fo", str(o), str(root / src)], check=True)
    b = o.read_bytes()
    assert b[4:20] != bytes(16), f"{entry}: unsigned DXIL (dxc without libdxil)"
    return b


out = ["// Generated by tools/gen_glassbody.py from shaders/glass_body.hlsl + glass_item.hlsl - do not edit.", "#pragma once",
       "#include <cstdint>", "", "namespace rf::glassarmor::shaders {"]
sizes = []
with tempfile.TemporaryDirectory() as td:
    for name, src, entry in (("kGlassBodyPs", "shaders/glass_body.hlsl", "PSGlassBody"), ("kGlassItemPs", "shaders/glass_item.hlsl", "PSGlassItem")):
        b = build(src, entry, td)
        rows = [", ".join(f"0x{x:02x}" for x in b[i:i + 20]) for i in range(0, len(b), 20)]
        out.append(f"inline constexpr uint8_t {name}[{len(b)}] = {{\n    " + ",\n    ".join(rows) + "\n};")
        sizes.append(f"{name} {len(b)} bytes")
out += ["} // namespace rf::glassarmor::shaders", ""]
(root / "src/GlassBodyShaders.h").write_text("\n".join(out))
print("wrote src/GlassBodyShaders.h (" + ", ".join(sizes) + "), shaders/glass_body_data.hlsli")
