#!/usr/bin/env python3
"""World FX: compile shaders/cloud_sea.hlsl + shaders/worldfx_pass.hlsl to signed DXIL (dxc) and write src/WorldFxShaders.h (byte arrays).
Usage: python3 tools/gen_worldfx.py [path/to/dxc] [--check]   (--check: compile only, unsigned is fine)"""
import pathlib, subprocess, sys, tempfile
root = pathlib.Path(__file__).resolve().parent.parent
args = [a for a in sys.argv[1:] if not a.startswith("--")]
dxc = args[0] if args else "dxc"
check = "--check" in sys.argv
entries = [("shaders/cloud_sea.hlsl", "VSCloudSea", "vs_6_0"), ("shaders/cloud_sea.hlsl", "PSCloudSea", "ps_6_0"),
           ("shaders/worldfx_pass.hlsl", "VSWorldFx", "vs_6_0"), ("shaders/worldfx_pass.hlsl", "PSWorldFx", "ps_6_0"),
           ("shaders/worldfx_pass.hlsl", "PSGlassRim", "ps_6_0")]   # the Novak Glass rim, its own pass
out = ["// Generated by tools/gen_worldfx.py from shaders/cloud_sea.hlsl - do not edit.", "#pragma once", "#include <cstdint>", "",
       "namespace rf::worldfx::shaders {"]
with tempfile.TemporaryDirectory() as td:
    for e in entries:
        src, entry, prof = e[:3]
        name = e[3] if len(e) > 3 else entry
        defs = [x for d in (e[4] if len(e) > 4 else []) for x in ("-D", d)]
        o = pathlib.Path(td) / f"{name}.dxil"
        subprocess.run([dxc, "-T", prof, "-E", entry, "-O3", *defs, "-Fo", str(o), str(root / src)], check=True)
        b = o.read_bytes()
        if not check:
            assert b[4:20] != bytes(16), f"{name}: unsigned DXIL (dxc without libdxil)"
        rows = [", ".join(f"0x{x:02x}" for x in b[i:i + 20]) for i in range(0, len(b), 20)]
        out.append(f"inline constexpr uint8_t {name}[{len(b)}] = {{\n    " + ",\n    ".join(rows) + "\n};")
out.append("} // namespace rf::worldfx::shaders\n")
if not check:
    (root / "src/WorldFxShaders.h").write_text("\n".join(out))
    print("wrote src/WorldFxShaders.h")
else:
    print("compiled OK")
