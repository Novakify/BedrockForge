#!/usr/bin/env python3
"""Create evidence-labelled JSON and Markdown conversion reports without running mod code."""
import argparse
import datetime
import hashlib
import json
import pathlib
import subprocess
import sys
from geckobridge_audit import audit
from geckobridge_compare import animations_from_jar, animations_from_rp, compare

def record(stage, status, detail, evidence=None):
    return {"stage":stage,"status":status,"detail":detail,"evidence":evidence or []}

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--jar",required=True)
    p.add_argument("--bedrock-rp",help="Optional already-generated RP; read-only comparison")
    p.add_argument("--out",required=True,help="Output directory for JSON and Markdown")
    p.add_argument("--vineflower",help="Path to user-installed Vineflower JAR; checks presence only")
    p.add_argument("--asm-report",help="Optional JSON generated by Java bytecode inspector")
    p.add_argument("--mapping",help="Optional mapping file; metadata check only")
    args=p.parse_args()
    jar=pathlib.Path(args.jar).resolve()
    if not jar.is_file(): p.error("Missing input JAR")
    out=pathlib.Path(args.out).resolve()
    out.mkdir(parents=True,exist_ok=True)
    jar_bytes=jar.read_bytes()
    inventory=audit(jar)
    checks=[record("source JAR","inspected","Static JAR and animation JSON parsed",["tools/geckobridge_audit.py"])]
    tools={}
    for name,value in (("vineflower",args.vineflower),("mapping-io input",args.mapping),("ASM analysis",args.asm_report)):
        if value:
            f=pathlib.Path(value).resolve()
            tools[name]={"configured":True,"exists":f.is_file(),"path":str(f)}
            checks.append(record(name,"configured" if f.is_file() else "unavailable","Present on disk; not executed or validated" if f.is_file() else "Specified file not found"))
        else:
            tools[name]={"configured":False}
            checks.append(record(name,"not_configured","Supply an explicit local path to enable this integration"))
    comparison=None
    if args.bedrock_rp:
        rp=pathlib.Path(args.bedrock_rp).resolve()
        if not rp.is_dir(): p.error("Missing --bedrock-rp directory")
        comparison=compare(animations_from_jar(jar),animations_from_rp(rp))
        checks.append(record("animation inventory","compared","Exact-name bone/channel presence compared; no animation fidelity conclusion",["tools/geckobridge_compare.py"]))
    else: checks.append(record("animation inventory","not_tested","No converted resource pack supplied"))
    for stage in ("Java controller translation","custom renderer parity","behavior parity","in-game validation"):
        checks.append(record(stage,"not_tested","Requires converter source, runtime integration or in-game evidence"))
    report={"schema_version":1,"generated_utc":datetime.datetime.now(datetime.timezone.utc).isoformat(),
       "input":{"name":jar.name,"sha256":hashlib.sha256(jar_bytes).hexdigest(),"size_bytes":len(jar_bytes)},
       "inventory":inventory,"tool_configuration":tools,"conversion_comparison":comparison,
       "checks":checks,"overall":"AUDIT_ONLY_NOT_CONVERSION_VERIFIED"}
    (out/"conversion_report.json").write_text(json.dumps(report,indent=2)+"\n",encoding="utf-8")
    lines=["# Java → Bedrock Conversion Audit","","**Overall:** AUDIT ONLY — conversion and in-game parity are not verified.","",
           "**Input:** `"+jar.name+"`", "**SHA-256:** `"+report["input"]["sha256"]+"`","",
           "## Feature status","","| Stage | Status | Evidence and limitations |","|---|---|---|"]
    for c in checks:
        lines.append("| "+c["stage"]+" | "+c["status"]+" | "+c["detail"].replace("|","/")+" |")
    lines.extend(["","## Animation inventory","", "```json",json.dumps(inventory["counts"],indent=2),"```",""])
    if comparison:
        lines.extend(["## Source/output comparison","",
             "Identical animation IDs are used for matching. Missing names may be renames, **not proven drops**.",
             "","- Source animations: "+str(comparison["source_animations"]),
             "- Output animations: "+str(comparison["output_animations"]),
             "- Unmatched source IDs: "+str(len(comparison["missing_animations"])),
             "- Unmatched output IDs: "+str(len(comparison["unmatched_output"])),""])
    lines.extend(["## Required next verification","",
                  "Run the real JavaModAnalyzer/ModPorter, collect ID mappings, inspect Java bytecode/controllers, validate interpolation and rendering, then test isolated Bedrock gameplay.","",
                  "No Java mod code or decompiler was executed by this report generator."])
    (out/"conversion_report.md").write_text("\n".join(lines)+"\n",encoding="utf-8")
    print(str(out/"conversion_report.md"))

if __name__=="__main__": main()
