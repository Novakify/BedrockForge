#!/usr/bin/env python3
"""Glass Armor: compile shaders/glass_armor.hlsl once per vanilla armor texture variant (material x layer) to signed
DXIL and write src/GlassArmorShaders.h (byte arrays + the table RF uses to recognise armor textures).

Data: tools/GlassArmor/vanilla_masks.json (alpha bits + mean colour of Mojang's armor textures).
Usage: python3 tools/gen_glassarmor.py [path/to/dxc] [--no-compile]
"""
import json
import pathlib
import subprocess
import sys
import tempfile

root = pathlib.Path(__file__).resolve().parent.parent
args = [a for a in sys.argv[1:] if not a.startswith("--")]
dxc = args[0] if args else "dxc"
compile_ = "--no-compile" not in sys.argv
data = json.loads((root / "tools/GlassArmor/vanilla_masks.json").read_text())
V = data["variants"]

# material look (approved preview v6): tint = faint glass colour, edge = neon outline
LOOK = {
    "leather": ("#8b5a2b", "#ff9a3c"), "chain": ("#9aa3ad", "#c9d8ea"), "iron": ("#dfe6f0", "#eef4ff"),
    "copper": ("#e0784a", "#ff7a3d"), "gold": ("#ffc83a", "#ffd23a"), "diamond": ("#4ff3ff", "#38f2ff"),
    "netherite": ("#4a3560", "#b14cff"),
}


def lin(h):
    def c(x):
        x /= 255.0
        return x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4
    return tuple(round(c(int(h[i:i + 2], 16)), 4) for i in (1, 3, 5))


def words(mask_hex):  # 32 rows x 64 bits -> 64 uint32, MSB = leftmost texel
    return [int(mask_hex[r * 16 + k * 8:r * 16 + k * 8 + 8], 16) for r in range(32) for k in range(2)]


def faces(cubes):
    out = []
    for u, v, w, h, d in cubes:
        out += [(u + d, v, w, d), (u + d + w, v, w, d), (u, v + d, d, h), (u + d, v + d, w, h), (u + d + w, v + d, d, h),
                (u + 2 * d + w, v + d, w, h)]
    return out


F1 = faces([(0, 0, 8, 8, 8), (32, 0, 8, 8, 8), (16, 16, 8, 12, 4), (40, 16, 4, 12, 4), (0, 16, 4, 12, 4)])
F2 = faces([(16, 16, 8, 12, 4), (0, 16, 4, 12, 4)])

hl = ["// Generated by tools/gen_glassarmor.py - do not edit.",
      f"static const uint kMasks[{len(V)}][64] = {{"]
for v in V:
    hl.append("    {" + ", ".join(f"0x{w:08x}u" for w in words(v["mask"])) + f"}}, // {v['mat']}_{v['layer']}")
hl.append("};")
# fused look: the class of every texel (0 line work, 1 shade, 2 fill, 3 highlight), 2 bits each, 16 per uint (MSB first)
RO = {(r["mat"], r["layer"]): r["roles"] for r in json.loads((root / "tools/GlassArmor/vanilla_roles.json").read_text())["variants"]}
hl.append(f"static const uint kRoles[{len(V)}][128] = {{")
for v in V:
    rh = RO[(v["mat"], v["layer"])]
    hl.append("    {" + ", ".join(f"0x{int(rh[k * 8:k * 8 + 8], 16):08x}u" for k in range(128)) + f"}}, // {v['mat']}_{v['layer']}")
hl.append("};")
hl.append(f"static const int4 kFaces1[{len(F1)}] = {{" + ", ".join(f"int4({a},{b},{c},{d})" for a, b, c, d in F1) + "};")
hl.append(f"static const int4 kFaces2[{len(F2)}] = {{" + ", ".join(f"int4({a},{b},{c},{d})" for a, b, c, d in F2) + "};")
(root / "shaders/glass_armor_data.hlsli").write_text("\n".join(hl) + "\n")

out = ["// Generated by tools/gen_glassarmor.py from shaders/glass_armor.hlsl - do not edit.", "#pragma once",
       "#include <cstdint>", "", "namespace rf::glassarmor::shaders {"]
blobs = []
with tempfile.TemporaryDirectory() as td:
    for idx, v in enumerate(V):
        name = f"PS_{v['mat']}_{v['layer']}"
        tint, edge = (lin(x) for x in LOOK[v["mat"]])
        # two builds per variant: plain Actor draws, and ActorGlint draws (enchanted: one more interpolant, the glint
        # layer UVs in TEXCOORD2, so the input signature differs)
        for glint in (0, 1):
            nm = name + ("_glint" if glint else "")
            if compile_:
                o = pathlib.Path(td) / f"{nm}.dxil"
                subprocess.run([dxc, "-T", "ps_6_0", "-E", "PSGlassArmor", "-O3", "-I", str(root / "shaders"),
                                f"-DGA_VARIANT={idx}", f"-DGA_LAYER={v['layer']}", f"-DGA_GLINT={glint}",
                                f"-DGA_LEATHER={1 if v['mat'] == 'leather' else 0}",
                                f"-DGA_TINT=float3({tint[0]},{tint[1]},{tint[2]})",
                                f"-DGA_EDGE=float3({edge[0]},{edge[1]},{edge[2]})",
                                "-Fo", str(o), str(root / "shaders/glass_armor.hlsl")], check=True)
                b = o.read_bytes()
                assert b[4:20] != bytes(16), f"{nm}: unsigned DXIL (dxc without libdxil)"
            else:
                b = b"\0"
            rows = [", ".join(f"0x{x:02x}" for x in b[i:i + 20]) for i in range(0, len(b), 20)]
            out.append(f"inline constexpr uint8_t {nm}[{len(b)}] = {{\n    " + ",\n    ".join(rows) + "\n};")
        blobs.append((name, v))
out.append("struct Variant { char const* mat; int layer; uint32_t mask[64]; uint8_t avg[3]; uint8_t const* ps; uint32_t psSize; uint8_t const* psGlint; uint32_t psGlintSize; };")
out.append(f"inline constexpr int kVariants = {len(V)};")
out.append("inline constexpr Variant kVariant[kVariants] = {")
for name, v in blobs:
    m = ", ".join(f"0x{w:08x}u" for w in words(v["mask"]))
    out.append(f"    {{\"{v['mat']}\", {v['layer']}, {{{m}}}, {{{v['avg'][0]}, {v['avg'][1]}, {v['avg'][2]}}}, {name}, sizeof({name}), {name}_glint, sizeof({name}_glint)}},")
out.append("};")
out.append("} // namespace rf::glassarmor::shaders\n")
(root / "src/GlassArmorShaders.h").write_text("\n".join(out))
print(f"wrote src/GlassArmorShaders.h ({len(V)} variants), shaders/glass_armor_data.hlsli")
