#!/usr/bin/env python3
"""Compile shaders/panel.hlsl to signed DXIL (dxc) and write src/PanelShaders.h (byte arrays).
Usage: python3 tools/gen_panel.py [path/to/dxc]   (needs dxc with libdxil for signing)"""
import pathlib, subprocess, sys, tempfile
root = pathlib.Path(__file__).resolve().parent.parent
dxc = sys.argv[1] if len(sys.argv) > 1 else "dxc"
entries = [("VSFull", "vs_6_0"), ("PSWorld", "ps_6_0"), ("VSPanel", "vs_6_0"), ("PSPanel", "ps_6_0")]
out = ["// Generated by tools/gen_panel.py from shaders/panel.hlsl - do not edit.", "#pragma once", "#include <cstdint>", "",
       "namespace rf::panel::shaders {"]
with tempfile.TemporaryDirectory() as td:
    for name, prof in entries:
        o = pathlib.Path(td) / f"{name}.dxil"
        subprocess.run([dxc, "-T", prof, "-E", name, "-O3", "-Fo", str(o), str(root / "shaders/panel.hlsl")], check=True)
        b = o.read_bytes()
        assert b[4:20] != bytes(16), f"{name}: unsigned DXIL (dxc without libdxil)"
        rows = [", ".join(f"0x{x:02x}" for x in b[i:i + 20]) for i in range(0, len(b), 20)]
        out.append(f"inline constexpr uint8_t {name}[{len(b)}] = {{\n    " + ",\n    ".join(rows) + "\n};")
out.append("} // namespace rf::panel::shaders\n")
(root / "src/PanelShaders.h").write_text("\n".join(out))
print("wrote src/PanelShaders.h")
