#!/usr/bin/env python3
"""Compile shaders/glyph.hlsl (LyricsFlow world text) to signed DXIL with dxc and write src/GlyphShaders.h.
Usage: python3 tools/gen_glyph.py [path/to/dxc]   (needs a dxc that signs: Windows SDK dxc.exe + dxil.dll, or a
DirectXShaderCompiler release with libdxil). CI runs this with the Windows SDK's dxc before the build; the generated
header is also committed so a PC build doesn't need dxc."""
import pathlib, subprocess, sys, tempfile
root = pathlib.Path(__file__).resolve().parent.parent
dxc = sys.argv[1] if len(sys.argv) > 1 else "dxc"
entries = [("VSGlyph", "vs_6_0"), ("PSGlyph", "ps_6_0"), ("VSComposite", "vs_6_0"), ("PSComposite", "ps_6_0")]
out = ["// Generated by tools/gen_glyph.py from shaders/glyph.hlsl - do not edit.", "#pragma once", "#include <cstdint>", "",
       "#define RF_HAVE_GLYPH_SHADERS 1", "namespace rf::lyrics::shaders {"]
with tempfile.TemporaryDirectory() as td:
    for name, prof in entries:
        o = pathlib.Path(td) / f"{name}.dxil"
        subprocess.run([dxc, "-T", prof, "-E", name, "-O3", "-Fo", str(o), str(root / "shaders/glyph.hlsl")], check=True)
        b = o.read_bytes()
        assert b[4:20] != bytes(16), f"{name}: unsigned DXIL (dxc without libdxil/dxil.dll)"
        rows = [", ".join(f"0x{x:02x}" for x in b[i:i + 20]) for i in range(0, len(b), 20)]
        out.append(f"inline constexpr uint8_t {name}[{len(b)}] = {{\n    " + ",\n    ".join(rows) + "\n};")
out.append("} // namespace rf::lyrics::shaders\n")
(root / "src/GlyphShaders.h").write_text("\n".join(out))
print("wrote src/GlyphShaders.h")

# LyricsFlow live sky (shaders/sky.hlsl + generated shaders/live_sky.hlsl) -> src/SkyShaders.h
out = ["// Generated by tools/gen_glyph.py from shaders/sky.hlsl - do not edit.", "#pragma once", "#include <cstdint>", "",
       "#define RF_HAVE_SKY_SHADERS 1", "namespace rf::lyrics::shaders {"]
with tempfile.TemporaryDirectory() as td:
    for name, prof in [("VSSky", "vs_6_0"), ("PSSky", "ps_6_0"), ("VSSkyQuad", "vs_6_0"), ("PSSkyQuad", "ps_6_0"),
                       ("VSSkyGame", "vs_6_0"), ("PSSkyGame", "ps_6_0"), ("VSSkyQuadGame", "vs_6_0"), ("PSSkyQuadGame", "ps_6_0")]:
        o = pathlib.Path(td) / f"{name}.dxil"
        src = "shaders/sky_game.hlsl" if name.endswith("Game") else "shaders/sky.hlsl"
        subprocess.run([dxc, "-T", prof, "-E", name, "-O3", "-Fo", str(o), str(root / src)], check=True)
        b = o.read_bytes()
        assert b[4:20] != bytes(16), f"{name}: unsigned DXIL (dxc without libdxil/dxil.dll)"
        rows = [", ".join(f"0x{x:02x}" for x in b[i:i + 20]) for i in range(0, len(b), 20)]
        out.append(f"inline constexpr uint8_t {name}[{len(b)}] = {{\n    " + ",\n    ".join(rows) + "\n};")
out.append("} // namespace rf::lyrics::shaders\n")
(root / "src/SkyShaders.h").write_text("\n".join(out))
print("wrote src/SkyShaders.h")
