# Regenerates src/FxTextures.h from Cinematic Interactions' fx textures (MIT, Southware), as in its 0.18.3 Fabric
# 1.21.11 jar (the version of the reference videos: the soft magic circle, not the later pixel circle).
# usage: python3 tools/gen_fx.py <path to assets/cinematic/textures/fx>
import sys, os
from PIL import Image
out = ['// Generated by tools/gen_fx.py from Cinematic Interactions (MIT, Southware): assets/cinematic/textures/fx/*.png',
       '#pragma once', '#include <cstdint>', 'namespace rf::cine::fxtex {']
for name, var in (('magic_circle', 'Magic'), ('glow', 'Glow'), ('beam', 'Beam')):
    im = Image.open(os.path.join(sys.argv[1], name + '.png')).convert('RGBA')
    w, h = im.size
    flat = [c for y in range(h) for x in range(w) for c in im.getpixel((x, y))]
    out += [f'inline constexpr int k{var}W = {w}, k{var}H = {h};', f'inline constexpr uint8_t k{var}[{w * h * 4}] = {{']
    out += ['    ' + ','.join(str(v) for v in flat[i:i + 32]) + ',' for i in range(0, len(flat), 32)]
    out += ['};']
out += ['}']
open('src/FxTextures.h', 'w').write('\n'.join(out) + '\n')
