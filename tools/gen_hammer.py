#!/usr/bin/env python3
# Builds src/HammerModel.h for Renderer Foundation from the Cinematic Interactions jar's hammer prop.
# "Just a Hammer" by RDiamonds (sketchfab.com/RDiamonds), CC BY 4.0; converted to Minecraft JSON by Southware.
import json, struct, sys, zlib, os
src, out = sys.argv[1], sys.argv[2]
def png(path):
    d = open(path, 'rb').read(); i = 8; chunks = {}; idat = b''; pal = None; trns = None
    while i < len(d):
        ln = struct.unpack('>I', d[i:i+4])[0]; t = d[i+4:i+8]; c = d[i+8:i+8+ln]; i += 12 + ln
        if t == b'IHDR': w, h, bd, ct = struct.unpack('>IIBB', c[:10])
        elif t == b'PLTE': pal = [tuple(c[k:k+3]) for k in range(0, len(c), 3)]
        elif t == b'tRNS': trns = list(c)
        elif t == b'IDAT': idat += c
    raw = zlib.decompress(idat)
    bpp = {3: 1, 6: 4, 2: 3, 4: 2, 0: 1}[ct]
    stride = (w * bd * (bpp if ct != 3 else 1) + 7) // 8
    if ct in (6, 2, 4): stride = w * bpp * bd // 8
    pix = []; prev = bytearray(stride); p = 0
    fb = max(1, (bd * (bpp if ct != 3 else 1)) // 8)
    for y in range(h):
        f = raw[p]; line = bytearray(raw[p+1:p+1+stride]); p += 1 + stride
        for x in range(stride):
            a = line[x-fb] if x >= fb else 0; b = prev[x]; cc = prev[x-fb] if x >= fb else 0
            if f == 1: line[x] = (line[x] + a) & 255
            elif f == 2: line[x] = (line[x] + b) & 255
            elif f == 3: line[x] = (line[x] + (a + b) // 2) & 255
            elif f == 4:
                pa, pb, pc = abs(b - cc), abs(a - cc), abs(a + b - 2 * cc)
                line[x] = (line[x] + (a if pa <= pb and pa <= pc else b if pb <= pc else cc)) & 255
        prev = line; row = []
        for x in range(w):
            if ct == 3:
                per = 8 // bd; byte = line[x // per]; idx = (byte >> (8 - bd * (x % per + 1))) & ((1 << bd) - 1)
                r, g, b = pal[idx]; a = trns[idx] if trns and idx < len(trns) else 255
            elif ct == 6: r, g, b, a = line[x*4:x*4+4]
            elif ct == 2: r, g, b = line[x*3:x*3+3]; a = 255
            else: raise SystemExit('unsupported png')
            row.append((r, g, b, a))
        pix.append(row)
    return w, h, pix
names = ['handle', 'head', 'pommel', 'collar']
place = {'handle': (0, 0), 'head': (32, 0), 'pommel': (0, 32), 'collar': (16, 32)}
atlas = [[(0, 0, 0, 0)] * 64 for _ in range(64)]
sizes = {}
for n in names:
    w, h, p = png(os.path.join(src, f'textures/item/prop/hammer_{n}.png')); sizes[n] = (w, h)
    ox, oy = place[n]
    for y in range(h):
        for x in range(w): atlas[oy+y][ox+x] = p[y][x]
m = json.load(open(os.path.join(src, 'models/prop/hammer.json')))
tex = {'#0': 'handle', '#1': 'head', '#2': 'pommel', '#3': 'collar'}
order = ['down', 'up', 'north', 'south', 'west', 'east']
L = ['// Generated by tools/gen_hammer.py from the Cinematic Interactions hammer prop - do not edit.',
     '// "Just a Hammer" by RDiamonds (https://sketchfab.com/3d-models/just-a-hammer-0b069177ed664af1b8efec018bc55cee),',
     '// licensed CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/). Converted to Minecraft JSON, UVs remapped and',
     '// scaled for the anvil by Southware (Cinematic Interactions, MIT); packed into one 64x64 atlas for Renderer Foundation.',
     '#pragma once', '#include <cstdint>', '', 'namespace rf::cine::hammer {',
     'struct Face { float u0, v0, u1, v1; int rot; }; // atlas pixels; order down, up, north, south, west, east',
     'struct Element { float from[3], to[3]; Face face[6]; };']
els = []
for e in m['elements']:
    fs = []
    for k in order:
        f = e['faces'][k]; n = tex[f['texture']]; w, h = sizes[n]; ox, oy = place[n]
        u0, v0, u1, v1 = f['uv']
        fs.append('{%.4ff, %.4ff, %.4ff, %.4ff, %d}' % (ox + u0 * w / 16, oy + v0 * h / 16, ox + u1 * w / 16, oy + v1 * h / 16, f.get('rotation', 0)))
    els.append('    {{%.4ff, %.4ff, %.4ff}, {%.4ff, %.4ff, %.4ff}, {%s}}' % (*e['from'], *e['to'], ', '.join(fs)))
L.append('inline constexpr Element kElements[%d] = {\n%s\n};' % (len(els), ',\n'.join(els)))
flat = [v for row in atlas for px in row for v in px]
rows = [', '.join(str(v) for v in flat[i:i+32]) for i in range(0, len(flat), 32)]
L.append('inline constexpr uint8_t kAtlas[64 * 64 * 4] = {\n    ' + ',\n    '.join(rows) + '\n};')
L.append('} // namespace rf::cine::hammer\n')
open(out, 'w').write('\n'.join(L))
print('wrote', out)
