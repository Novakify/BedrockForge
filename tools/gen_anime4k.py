#!/usr/bin/env python3
"""Convert Anime4K's mpv GLSL CNN shaders (bloc97/Anime4K, MIT) to HLSL pixel shaders + a C++ pass table.

Usage: python3 -I tools/gen_anime4k.py path/to/Anime4K   (a checkout of https://github.com/bloc97/Anime4K)
Writes shaders/anime4k.hlsl and src/Anime4KPasses.h (both committed, so CI and PC builds don't need the checkout).

Video screen upscaling (ScreenPass.cpp) runs one or two stages per new video frame:
  Restore CNN (cleans compression blur / ringing on the line art, same resolution)
  Upscale CNN x2 (doubles the resolution; only when the source is clearly smaller than the 1920x1080 screen)
"Sharp" = Restore S + Upscale x2 S, "Max" = Restore M + Upscale x2 M.

Conversion rules (mpv hook -> HLSL), every pass is one full-screen pixel shader:
  X_texOff(vec2(a, b)) -> point sample of the bound texture X at this pixel + (a, b)   (conv passes keep the size)
  X_tex(X_pos)         -> sample of X at this pixel's uv (linear: MAIN is upsampled bilinearly by the x2 stage)
  mat4(16 floats) * v  -> mul(v, float4x4(16 floats))   (GLSL fills columns, HLSL rows: same maths)
  Depth-to-Space       -> hand-written (each 2x2 output block takes the 4 channels of one conv texel)
"""
import pathlib, re, sys

root = pathlib.Path(__file__).resolve().parent.parent
src = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "Anime4K")
STAGES = [  # (id, file, label)
    ("RS", "glsl/Restore/Anime4K_Restore_CNN_S.glsl", "Restore CNN (S)"),
    ("US", "glsl/Upscale/Anime4K_Upscale_CNN_x2_S.glsl", "Upscale CNN x2 (S)"),
    ("RM", "glsl/Restore/Anime4K_Restore_CNN_M.glsl", "Restore CNN (M)"),
    ("UM", "glsl/Upscale/Anime4K_Upscale_CNN_x2_M.glsl", "Upscale CNN x2 (M)"),
]
MAX_BIND = 8


def passes(text):
    out, cur = [], None
    for line in text.splitlines():
        if line.startswith("//!DESC"):
            cur = {"desc": line[8:].strip(), "bind": [], "save": None, "width": None, "body": []}
            out.append(cur)
        elif cur is None:
            continue
        elif line.startswith("//!BIND"):
            cur["bind"].append(line.split()[1])
        elif line.startswith("//!SAVE"):
            cur["save"] = line.split()[1]
        elif line.startswith("//!WIDTH"):
            cur["width"] = line.split()[1:]
        elif line.startswith("//!"):
            continue
        else:
            cur["body"].append(line)
    return out


def convert(stage, i, p):
    binds = p["bind"]
    assert 1 <= len(binds) <= MAX_BIND, (stage, i, binds)
    name = f"A4K_{stage}_{i}"
    reg = {b: k for k, b in enumerate(binds)}
    body = "\n".join(p["body"]).strip()
    two_x = p["width"] and len(p["width"]) >= 3 and p["width"][1] == "2" and p["width"][2] == "*"
    if "Depth-to-Space" in p["desc"]:
        assert two_x and binds == ["MAIN", "conv2d_last_tf"], (stage, i, binds)
        code = ("    int2  q  = int2(pos.xy);\n"
                "    float c0 = T1.Load(int3(q / 2, 0))[(q.y & 1) * 2 + (q.x & 1)];\n"
                "    return float4(c0, c0, c0, c0) + T0.SampleLevel(sLin, uv, 0);")
    else:
        assert not two_x, (stage, i)
        # texture access first (inside the #defines), then the maths
        def tex_off(m):
            return f"TEXOFF(T{reg[m.group(1)]}, {m.group(2)}, {m.group(3)})"
        body = re.sub(r"(\w+?)_texOff\(vec2\(([^,]+),\s*([^)]+)\)\)", tex_off, body)
        body = re.sub(r"(\w+?)_tex\(\1_pos\)", lambda m: f"TEXAT(T{reg[m.group(1)]})", body)
        body = re.sub(r"mat4\(([^)]*)\)\s*\*\s*(go_\d+\([^)]*\)|g_\d+)", r"mul(\2, float4x4(\1))", body)
        body = body.replace("vec4", "float4").replace("vec2", "float2")
        assert "_tex" not in body and "mat4" not in body and "ivec" not in body, (stage, i, body[:400])
        defs = [l for l in body.splitlines() if l.startswith("#define")]
        rest = [l for l in body.splitlines() if not l.startswith("#define")]
        assert rest[0].startswith("float4 hook()") and rest[-1] == "}", (stage, i)
        code_lines = rest[1:-1]
        undefs = [f"#undef {d.split()[1].split('(')[0]}" for d in defs]
        code = "\n".join(code_lines)
        return name, binds, p["save"], two_x, p["desc"], "\n".join(defs) + "\n" + \
            f"float4 {name}(float4 pos : SV_Position) : SV_Target {{\n    float2 uv = pos.xy * pt;\n{code}\n}}\n" + "\n".join(undefs)
    return name, binds, p["save"], two_x, p["desc"], \
        f"float4 {name}(float4 pos : SV_Position) : SV_Target {{\n    float2 uv = pos.xy * pt;\n{code}\n}}"


hlsl = ["// Generated by tools/gen_anime4k.py from Anime4K's GLSL shaders - do not edit.",
        "// Anime4K by bloc97 - MIT License, Copyright (c) 2019-2021 bloc97 (full text: third_party/Anime4K-LICENSE.txt).",
        "// One pixel shader per mpv hook pass. t0..t7 = the pass's bound textures in //!BIND order, s0 point, s1 linear clamp.",
        "// b0: outSize (px), pt = 1 / outSize. Conv passes are the size of their inputs, so the pixel's uv addresses them too.",
        "cbuffer A4K : register(b0) { float2 outSize; float2 pt; float4 a4kSpare; };",
        "Texture2D T0 : register(t0); Texture2D T1 : register(t1); Texture2D T2 : register(t2); Texture2D T3 : register(t3);",
        "Texture2D T4 : register(t4); Texture2D T5 : register(t5); Texture2D T6 : register(t6); Texture2D T7 : register(t7);",
        "SamplerState sPt : register(s0);",
        "SamplerState sLin : register(s1);",
        "#define TEXOFF(T, x, y) T.SampleLevel(sPt, uv + float2(x, y) * pt, 0)",
        "#define TEXAT(T) T.SampleLevel(sLin, uv, 0)",
        "float4 A4K_VS(uint id : SV_VertexID) : SV_Position {",
        "    float2 p = float2((id << 1) & 2, id & 2);",
        "    return float4(p * float2(2, -2) + float2(-1, 1), 0, 1);",
        "}", ""]
table = []
for stage, path, label in STAGES:
    ps = passes((src / path).read_text())
    for i, p in enumerate(ps):
        name, binds, save, two_x, desc, code = convert(stage, i, p)
        hlsl.append(f"// {desc}")
        hlsl.append(code)
        hlsl.append("")
        b = ", ".join(f'"{x}"' for x in binds)
        table.append(f'    {{"{stage}", "{name}", {len(binds)}, {{{b}}}, "{save}", {"2" if two_x else "1"}}}, // {desc}')

(root / "shaders/anime4k.hlsl").write_text("\n".join(hlsl) + "\n")
entries = [t.split('"')[3] for t in table]
hdr = ["// Generated by tools/gen_anime4k.py - do not edit. Anime4K by bloc97 (MIT), see shaders/anime4k.hlsl.",
       "#pragma once", "#include <cstdint>", "", "namespace rf::screen {",
       "struct A4kPass {",
       "    char const* stage;     // RS / US (Sharp), RM / UM (Max)",
       "    char const* entry;     // pixel shader entry in shaders/anime4k.hlsl (ScreenShaders.h: shaders::<entry>)",
       "    uint32_t    bindCount;",
       "    char const* bind[8];   // texture names; MAIN = the stage's input",
       "    char const* save;      // output name; MAIN = the stage's result",
       "    uint32_t    scale;     // 1 = size of bind[0]'s texture... see ScreenPass.cpp; 2 = twice the stage input (x2)",
       "};",
       "inline constexpr A4kPass kA4kPasses[] = {"] + table + ["};",
       f"inline constexpr uint32_t kA4kPassCount = {len(table)};",
       "} // namespace rf::screen", ""]
(root / "src/Anime4KPasses.h").write_text("\n".join(hdr))
(root / "tools/anime4k_entries.txt").write_text("\n".join(entries) + "\n")
print(f"wrote shaders/anime4k.hlsl, src/Anime4KPasses.h ({len(table)} passes)")
