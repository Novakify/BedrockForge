import sys, os, glob, struct
from lazurite.material import buffer as B
from lazurite.material import platform as P
_r, _w = B.Buffer.read, B.Buffer.write
B.Buffer.read = lambda s, f, v: _r(s, f, 25 if v == 26 else v)
B.Buffer.write = lambda s, f, v: _w(s, f, 25 if v == 26 else v)
_pm = P.ShaderPlatform._platform_mapping.__func__
P.ShaderPlatform._platform_mapping = classmethod(lambda cls, v: _pm(cls, 25 if v == 26 else v))
from lazurite.material import Material

def fnv(b):
    h = 0xcbf29ce484222325
    for x in b:
        h = ((h ^ x) * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return h

D = sys.argv[1]
if len(sys.argv) > 2 and sys.argv[2] == "probe":
    m = Material.load_bin_file(os.path.join(D, "PopulateVolume.material.bin"))
    s = m.passes[0].variants[0].shaders[0]
    print([q.name for q in m.passes]); print([a for a in dir(s) if not a.startswith('_')])
    print(s.stage, s.platform); b = s.bgfx_shader; print([a for a in dir(b) if not a.startswith('_')])
    u = b.uniforms[0] if b.uniforms else None; print([a for a in dir(u) if not a.startswith('_')] if u else None)
    sys.exit()

ROLES = ["SkyZenithColor", "SkyHorizonColor", "SunColor", "MoonColor", "DirectionalLightSourceDiffuseColorAndIlluminance",
         "SkyAmbientLightColorIntensity", "FogColor", "HeightFogScaleBias", "AirAlbedoExtinction",
         "u_view", "u_invView", "SunDir", "MoonDir", "DirectionalLightSourceWorldSpaceDirection"]
NPATCH = 9
rows = {}
names = {}
for f in sorted(glob.glob(os.path.join(D, "*.material.bin"))):
    mat = os.path.basename(f)[:-len(".material.bin")]
    if not (mat.startswith("Deferred") or mat.startswith("SkyProbe") or mat == "PopulateVolume"):
        continue
    m = Material.load_bin_file(f)
    for p in m.passes:
        for v in p.variants:
            for s in v.shaders:
                plat, stage = str(s.platform).split(".")[-1], str(s.stage).split(".")[-1]
                if plat not in ("Direct3D_SM60", "Direct3D_SM65") or stage not in ("Fragment", "Compute"):
                    continue
                b = s.bgfx_shader
                raw = bytes(b.shader_bytes)
                i = raw.find(b"DXBC")
                if i < 0:
                    continue
                size = struct.unpack_from("<I", raw, i + 24)[0]
                h = fnv(raw[i:i + size])
                off = [-1] * len(ROLES)
                for u in b.uniforms:
                    if u.name in ROLES and u.type_bits != 48:
                        off[ROLES.index(u.name)] = u.reg_index
                if all(o < 0 for o in off[:NPATCH]) or all(o < 0 for o in off[NPATCH:]):
                    continue
                rows[h] = (b.size, off, 1 if stage == "Compute" else 0)
                names.setdefault(f"{mat}/{p.name}", 0)
                names[f"{mat}/{p.name}"] += 1
out = ["// Generated by tools/gen_vvlive_table.py from the game's data/renderer/materials (MC 1.26.51.01) - do not edit.",
       "// One row per SM6.0 / SM6.5 fragment or compute shader of VV's lighting, sky-probe and fog-volume materials:",
       "// FNV-1a 64 of the DXBC container, the size of its uniforms, and the byte offset of each uniform RF knows (-1 = none).",
       "#pragma once", "#include <cstdint>", "", "namespace rf::vvlive::table {",
       "enum Role : int { Zen, Hor, Sun, Moon, DirLight, SkyAmb, FogCol, HeightFog, AirAlbedo, UView, UInvView, SunDir, MoonDir, DirLightDir, RoleCount };",
       "struct Row { uint64_t hash; uint16_t size; uint8_t compute; int16_t off[RoleCount]; };",
       "// " + ", ".join(f"{k} x{n}" for k, n in sorted(names.items())),
       f"inline constexpr Row kRows[{len(rows)}] = {{"]
for h in sorted(rows):
    size, off, comp = rows[h]
    out.append(f"    {{0x{h:016x}ull, {size}, {comp}, {{{', '.join(str(o) for o in off)}}}}},")
out += ["};", "} // namespace rf::vvlive::table", ""]
open(sys.argv[2], "w").write("\n".join(out))
print(len(rows), "rows;", ", ".join(f"{k} x{n}" for k, n in sorted(names.items())))
