-- FiguraBridge math self-test (Vector2/3/4, Matrix2/3/4, vectors / matrices APIs) against Figura 0.1.6 semantics.
-- Run: COVERAGE=tests/figura/math_test.lua Sim <compiled_dir> coverage out.json
local pass, fail = 0, 0
local function check(name, got, want)
  local ok
  if type(want) == "number" and type(got) == "number" then
    ok = math.abs(got - want) <= 1e-9 * math.max(1, math.abs(want))
  else
    ok = tostring(got) == tostring(want)
  end
  if ok then pass = pass + 1 else fail = fail + 1; print("FAIL " .. name .. ": got " .. tostring(got) .. ", want " .. tostring(want)) end
end
local function err(name, f, pat)
  local ok, e = pcall(f)
  if ok then fail = fail + 1; print("FAIL " .. name .. ": no error") return end
  if pat and not tostring(e):find(pat, 1, true) then fail = fail + 1; print("FAIL " .. name .. ": " .. tostring(e)) return end
  pass = pass + 1
end

